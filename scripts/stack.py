"""Render the stack page from data/stack.json, and check that it is exhaustive.

With no arguments, rewrites the marker block in pydevices/docs/stack.md. The
page's text outside the block is the pydevices repository's own.

--check compares data/stack.json with sibling checkouts and fails on anything
a repository holds that has no row, and on any row whose files are gone.
--index-json and --repos-json add the mip index and the organization's
repository list to the comparison; the stack-check workflow passes both.
--stale also fails when the page differs from what the data renders.
"""
import argparse
import fnmatch
import json
import os
import sys
import tomllib

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))
STACK_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'stack.json')
PAGE = ('pydevices', 'docs/stack.md')
START = '<!-- PYDEVICES-STACK: START -->'
END = '<!-- PYDEVICES-STACK: END -->'
# The repository name on GitHub, where its checkout's folder differs.
CHECKOUT = {'.github': 'dotgithub'}


def checkout(root, repo):
    return os.path.join(root, CHECKOUT.get(repo, repo))


def slug(title):
    """The anchor both GitHub and MyST give a heading."""
    kept = ''.join(c for c in title.lower() if c.isalnum() or c in ' -')
    return kept.replace(' ', '-')


def blob_url(repo, path):
    return f'https://github.com/PyDevices/{repo}/blob/main/{path}'


def tree_url(repo, path):
    return f'https://github.com/PyDevices/{repo}/tree/main/{path}'


def entry_link(entry):
    """Where an entry's name points: its guide, then its page, then its source."""
    guide = entry.get('guide')
    if guide:
        repo, _, path = guide.rpartition(':')
        return blob_url(repo or entry['repo'], path)
    if entry.get('web'):
        return entry['web']
    path = entry['path']
    if path.endswith(('.py', '.md', '.toml')):
        return blob_url(entry['repo'], path)
    return tree_url(entry['repo'], path)


def render_get(entry, words):
    """How to get an entry: 'mip:x' and 'pip:x' name a package, the rest a word."""
    parts = []
    for item in entry['get']:
        kind, _, name = item.partition(':')
        if name:
            parts.append(f'`{kind} {name}`')
        else:
            parts.append(words[kind])
    return ', '.join(parts)


def build_block(stack):
    lines = [START,
             '<!-- Generated by dotgithub/scripts/stack.py from data/stack.json.',
             '     Do not edit between these markers; edit the data instead. -->',
             '']
    groups = stack['groups']
    by_group = {g['id']: [] for g in groups}
    for entry in stack['entries']:
        by_group[entry['group']].append(entry)

    lines += ['## What do you want to do?', '']
    for group in groups:
        lines.append(f'- [I want to {group["want"]}](#{slug(group["title"])})')
    lines.append('')

    for group in groups:
        lines += [f'## {group["title"]}', '']
        for entry in by_group[group['id']]:
            name = f'[`{entry["name"]}`]({entry_link(entry)})'
            get = render_get(entry, stack['get'])
            lines += [f'- {name}: {entry["does"]}\\',
                      f'  Get it: {get}. Runs on: {entry["runs"]}.']
        lines.append('')

    titles = {g['id']: g['title'] for g in groups}
    lines += ['## A to Z', '']
    by_letter = {}
    for entry in sorted(stack['entries'], key=lambda e: e['name'].lower().lstrip('.')):
        link = f'[`{entry["name"]}`](#{slug(titles[entry["group"]])})'
        by_letter.setdefault(entry['name'].lstrip('.')[0].upper(), []).append(link)
    for letter, links in by_letter.items():
        lines.append(f'- **{letter}:** {", ".join(links)}')
    lines += ['', END]
    return '\n'.join(lines)


def page_with_block(content, block):
    if START not in content or END not in content:
        raise SystemExit(f'{PAGE[1]}: no {START} marker block')
    head, rest = content.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def scan_tree(root, rule):
    """What a scan rule finds: files and folders that hold something."""
    repo_dir = checkout(root, rule['repo'])
    folder, _, pattern = rule['glob'].rpartition('/')
    full = os.path.join(repo_dir, folder)
    if not os.path.isdir(full):
        return None
    found = []
    for name in sorted(os.listdir(full)):
        if name.startswith(('.', '_')) and name != '__init__.py':
            continue
        if name == '__pycache__' or name.endswith('.egg-info'):
            continue
        if not fnmatch.fnmatch(name, pattern):
            continue
        path = os.path.join(full, name)
        # A folder with only hidden files is what a removed package leaves.
        if os.path.isdir(path) and not any(
            not n.startswith('.') and n != '__pycache__' for n in os.listdir(path)
        ):
            continue
        found.append(f'{folder}/{name}')
    return found


def check_tree(stack, root):
    """Every problem between the data and the checkouts under ``root``."""
    problems = []
    ids = {g['id'] for g in stack['groups']}
    listed = set()
    names = set()
    for entry in stack['entries']:
        name = entry['name']
        if name in names:
            problems.append(f'{name}: listed twice')
        names.add(name)
        if entry['group'] not in ids:
            problems.append(f'{name}: no group {entry["group"]}')
        for item in entry['get']:
            kind, _, package = item.partition(':')
            if kind not in stack['get'] and not (package and kind in ('mip', 'pip')):
                problems.append(f'{name}: unknown way to get it, {item}')
        repo_dir = checkout(root, entry['repo'])
        if os.path.isdir(repo_dir):
            if not os.path.exists(os.path.join(repo_dir, entry['path'])):
                problems.append(f'{name}: {entry["repo"]}/{entry["path"]} is gone')
            listed.add(f'{entry["repo"]}:{entry["path"]}')
        guide = entry.get('guide')
        if guide:
            repo, _, path = guide.rpartition(':')
            repo = repo or entry['repo']
            guide_dir = checkout(root, repo)
            if os.path.isdir(guide_dir) and not os.path.exists(os.path.join(guide_dir, path)):
                problems.append(f'{name}: guide {repo}/{path} is gone')

    for rule in stack['scan']:
        found = scan_tree(root, rule)
        if found is None:
            problems.append(f'{rule["repo"]}: nothing to scan at {rule["glob"]}')
            continue
        for path in found:
            key = f'{rule["repo"]}:{path}'
            if key not in listed and key not in stack['not_listed']:
                problems.append(f'{key} has no row in data/stack.json')
    return problems


def check_index(stack, root, index):
    """Every package in the mip index has a row, and every row's package exists."""
    published = {p['name'] for p in index['packages']}
    claimed = {
        item.partition(':')[2]
        for entry in stack['entries'] for item in entry['get'] if item.startswith('mip:')
    }
    problems = [f'{name}: mip package is not in the index'
                for name in sorted(claimed - published)]
    pydevices = checkout(root, 'pydevices')
    with open(os.path.join(pydevices, 'drivers', 'drivers.toml'), 'rb') as f:
        drivers = set(tomllib.load(f))
    boards = set()
    for _, folders, _ in os.walk(os.path.join(pydevices, 'board_configs')):
        boards.update(folders)
    for name in sorted(published - claimed - drivers - boards):
        problems.append(f'{name}: in the mip index with no row in data/stack.json')
    return problems


def check_repos(stack, repos):
    """Every public repository that isn't archived has a row."""
    listed = {entry['repo'] for entry in stack['entries']}
    return [f'{repo["name"]}: public repository with no row in data/stack.json'
            for repo in repos
            if not repo.get('isArchived') and repo['name'] not in listed
            and repo['name'] not in stack['repos_not_listed']]


def load_stack():
    with open(STACK_PATH, encoding='utf-8') as f:
        return json.load(f)


def write_page(stack, root=BASE_DIR, page=None):
    """Rewrite the marker block; returns False when the page isn't checked out."""
    path = page or os.path.join(checkout(root, PAGE[0]), PAGE[1])
    if not os.path.exists(path):
        print(f'[SKIP] Stack page missing: {path}')
        return False
    with open(path, encoding='utf-8') as f:
        content = f.read()
    with open(path, 'w', encoding='utf-8') as f:
        f.write(page_with_block(content, build_block(stack)))
    print(f'[OK] Stack page -> {os.path.relpath(path, root)}')
    return True


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--root', default=BASE_DIR, help='folder holding the sibling checkouts')
    parser.add_argument('--page', help='write or compare this file instead of the pydevices page')
    parser.add_argument('--check', action='store_true', help='compare the data with the checkouts')
    parser.add_argument('--stale', action='store_true', help='fail if the page differs from the data')
    parser.add_argument('--index-json', help='the mip index, for --check')
    parser.add_argument('--repos-json', help='a list of {name, isArchived}, for --check')
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    stack = load_stack()
    if not args.check:
        write_page(stack, args.root, args.page)
        return 0

    problems = check_tree(stack, args.root)
    if args.index_json:
        with open(args.index_json, encoding='utf-8') as f:
            problems += check_index(stack, args.root, json.load(f))
    if args.repos_json:
        with open(args.repos_json, encoding='utf-8') as f:
            problems += check_repos(stack, json.load(f))
    if args.stale:
        path = args.page or os.path.join(checkout(args.root, PAGE[0]), PAGE[1])
        with open(path, encoding='utf-8') as f:
            content = f.read()
        if page_with_block(content, build_block(stack)) != content:
            problems.append(f'{path}: differs from data/stack.json; run scripts/stack.py')
    for problem in problems:
        print(problem)
    print(f'{len(stack["entries"])} rows, {len(problems)} problems')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
